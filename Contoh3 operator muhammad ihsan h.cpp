/* Penggunaan Notasi Didepan Variabel*/
#include <iostream>
using namespace std;
int main()
{
int a = 10, b = 5;
printf("Nilai A = %d", a);
printf("\nNilai ++A = %d", ++a);
printf("\nNilai A = %i", a);
printf("\nNilai B = %i", b);
printf("\nNilai --B = %i", --b);
printf("\nNilai B = %i", b);
return 0;
}
